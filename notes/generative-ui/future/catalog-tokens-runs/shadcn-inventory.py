#!/usr/bin/env python3
"""
shadcn/ui inventory — how many components are we actually talking about when we
say "the FULL shadcn/ui library"? Three counts, three sources, plus a name diff.

Read-only. Run:
    python3 /Users/work/ai/notes/generative-ui/future/catalog-tokens-runs/shadcn-inventory.py
"""
import os, re, json, glob

REPO = "/Users/work/open-generative"
UPSTREAM = f"{REPO}/vendor/shadcn-ui"
UI_DIR = f"{UPSTREAM}/apps/v4/registry/new-york-v4/ui"
INDEX = f"{UPSTREAM}/apps/v4/registry/__index__.tsx"
COMPARE_UI = f"{REPO}/apps/compare/src/components/ui"
MANIFEST = "/tmp/oui-adoption/manifest.json"


def registry_files(path: str) -> list[str]:
    names = []
    for p in sorted(glob.glob(f"{path}/*.tsx")):
        base = os.path.basename(p)[:-4]
        if base.startswith("_") or base.endswith(".test") or base == "index":
            continue
        names.append(base)
    return names


def index_ui_names() -> list[str]:
    """Names under registry/new-york-v4/ui/ as recorded by the autogenerated index."""
    if not os.path.exists(INDEX):
        return []
    src = open(INDEX, encoding="utf-8").read()
    return sorted(set(re.findall(r'path: "registry/new-york-v4/ui/([a-z0-9-]+)\.tsx"', src)))


def ours() -> list[str]:
    """Our 60 `ui.*` contract families (from the generator manifest)."""
    try:
        m = json.load(open(MANIFEST, encoding="utf-8"))
        return m["c1"]["componentNames"]
    except Exception:
        return []


def main() -> None:
    up = registry_files(UI_DIR)
    idx = index_ui_names()
    cmp_ = registry_files(COMPARE_UI)
    manifest = ours()
    # manifest names are PascalCase OpenUI names -> kebab for comparison
    our_kebab = sorted(
        re.sub(r"(?<!^)(?=[A-Z])", "-", n).lower().replace("layout-stack", "layout.stack")
        for n in manifest
    )
    our_kebab = [n for n in our_kebab if n != "layout.stack"]

    print("shadcn/ui component inventory")
    print("=" * 70)
    print(f"upstream registry files   {UI_DIR}")
    print(f"    -> {len(up)} components")
    print(f"upstream registry index   {INDEX}")
    print(f"    -> {len(idx)} entries whose files[].path is registry/new-york-v4/ui/*.tsx")
    print(f"apps/compare installed    {COMPARE_UI}")
    print(f"    -> {len(cmp_)} components")
    print(f"our contracts             packages/components/src/ui.ts -> {len(our_kebab)} ui.* families")
    print()
    print("upstream == index ?", "YES" if set(up) == set(idx) else f"NO  (only-upstream={sorted(set(up)-set(idx))}, only-index={sorted(set(idx)-set(up))})")
    print()

    print("-- our 60 ui.* families --")
    print(" ".join(our_kebab))
    print()
    print("-- upstream shadcn ui/ files not covered by our 60 --")
    print(" ".join(sorted(set(up) - set(our_kebab))) or "(none)")
    print("-- our families with no upstream ui/ file of that name --")
    print(" ".join(sorted(set(our_kebab) - set(up))) or "(none)")
    print()
    print("-- apps/compare installed (the demo's actual copy) --")
    print(" ".join(cmp_))
    print("-- installed but not in our 60 --", " ".join(sorted(set(cmp_) - set(our_kebab))) or "(none)")
    print()

    out = {
        "upstreamUiDir": UI_DIR,
        "upstreamCount": len(up),
        "upstreamNames": up,
        "registryIndexCount": len(idx),
        "compareCount": len(cmp_),
        "compareNames": cmp_,
        "ourFamilyCount": len(our_kebab),
        "ourFamilies": our_kebab,
        "upstreamNotInOurs": sorted(set(up) - set(our_kebab)),
        "oursNotInUpstream": sorted(set(our_kebab) - set(up)),
    }
    dst = "/tmp/oui-adoption/shadcn-inventory.json"
    os.makedirs("/tmp/oui-adoption", exist_ok=True)
    json.dump(out, open(dst, "w", encoding="utf-8"), indent=2)
    print("wrote", dst)


if __name__ == "__main__":
    main()
